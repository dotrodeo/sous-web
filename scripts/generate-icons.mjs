const WORDMARK_WIDTH = 328

/** The hat on a 100x100 grid, optionally scaled about the center (maskable icons). */
function hat(scale = 1) {
    const t = scale === 1 ? '' : ` transform="translate(50 50) scale(${scale}) translate(-50 -50)"`
    const b = HAT_BAND
    return (
        `<g${t}><path d="${HAT_PUFF}" fill="${SUNFLOWER}"/>` +
        `<path d="${HAT_PLEATS}" stroke="${COBALT}" stroke-width="3.5" stroke-linecap="round"/>` +
        `<rect x="${b.x}" y="${b.y}" width="${b.width}" height="${b.height}" rx="${b.rx}" fill="${SUNFLOWER}"/></g>`
    )
}

/** 'tile': rounded tile with transparent corners. 'square': full bleed (the OS applies its own mask). */
function mark(shape, scale = 1) {
    const bg =
        shape === 'tile'
            ? `<rect x="2" y="2" width="96" height="96" rx="23" fill="${COBALT}"/>`
            : `<rect width="100" height="100" fill="${COBALT}"/>`
    return bg + hat(scale)
}

const svg = (inner, width, height, viewBox) =>
    `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="${viewBox}">${inner}</svg>\n`

const wordmark = () => {
    const letters = WORDMARK_LETTERS.map(
        ([x, s, d]) => `<path transform="translate(${x} 76) scale(${s})" d="${d}"/>`,
    ).join('')
    return svg(
        `${mark('tile')}<g fill="${INK}">${letters}</g>`,
        Math.round((92 * WORDMARK_WIDTH) / 100),
        92,
        `0 0 ${WORDMARK_WIDTH} 100`,
    )
}

