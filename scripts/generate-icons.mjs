const tmp = await mkdtemp(path.join(tmpdir(), 'sous-icons-'))
try {
    for (const [file, size, shape, scale] of PNGS) {
        const src = path.join(tmp, `${file}.svg`)
        await writeFile(src, svg(mark(shape, scale), size, size, '0 0 100 100'))
        execFileSync(
            chrome,
            [
                '--headless',
                '--no-sandbox',
                '--hide-scrollbars',
                '--default-background-color=00000000',
                `--window-size=${size},${size}`,
                `--screenshot=${new URL(file, icons).pathname}`,
                `file://${src}`,
            ],
            { stdio: 'ignore' },
        )
        console.log('wrote', file)
    }
} finally {
    await rm(tmp, { recursive: true, force: true })
}
